def main() -> None:
    stories = json.loads(DATA.read_text(encoding="utf-8"))
    if isinstance(stories, dict):
        stories = stories.get("stories", stories)
    before = len(stories)

    # 1. 删除三国故事
    kept = [s for s in stories if s.get("title") not in REMOVE_TITLES]
    removed = [s["title"] for s in stories if s.get("title") in REMOVE_TITLES]

    # 2. 跳过已存在的新故事，追加缺失的
    existing = {s.get("title") for s in kept}
    next_id = 1 + max(int(s["id"].split("_")[1]) for s in kept)
    added = []
    for st in NEW_STORIES:
        if st["title"] in existing:
            continue
        rec = {
            "id": f"story_{next_id:03d}",
            "type": "story",
            "title": st["title"],
            "cover": "",
            "icon": st["icon"],
            "category": st["category"],
            "age": st["age"],
            "duration": st["duration"],
            "text": st["text"],
            "audio": f"assets/audio/story_{next_id:03d}.mp3",
            "source": st["source"],
            "license": "公共领域",
            "series": st["series"] or None,
        }
        kept.append(rec)
        added.append((rec["id"], rec["title"]))
        existing.add(st["title"])
        next_id += 1

    # 3. 写回
    DATA.write_text(json.dumps(kept, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"删除 {len(removed)} 篇: {removed}")
    print(f"新增 {len(added)} 篇: {added}")
    print(f"总数 {before} → {len(kept)}")


if __name__ == "__main__":
    main()
